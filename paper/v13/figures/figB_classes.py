#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""figB_classes.pdf -- appendix: the best arm trained SEPARATELY on each substructure class.

Three rows (axion / cdm / no_sub).  Each row shows two held-out images of that class and
three images generated by an IQP-affine (M = 4, MMD-flat, resample prior, N = 100, seed 0)
run trained on 100 images of that class alone.  Every panel is on ONE linear magma scale,
vmin = 0, vmax = 1, so rows and columns are directly comparable.

SELECTION RULE (fixed in advance, no cherry-picking): the first two held-out images and the
first three generated frames of each run, in index order -- held-out i = 0, 1 and
generated_000/001/002.npy.  Nothing is reordered or screened for ring quality.

Reads only committed artefacts:
    experiments/13_iqp_turbulence_replication/outputs_lens_class/<class>_m4_mmdflat_resample_n100/
    the per-class held-out split, via data_lens_class.install(<class>) + data_lens_r3.load_r3
Writes only into this directory.  CPU, seconds.  Python 3.9 compatible.
"""
from __future__ import annotations

import os
import sys

import numpy as np

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt                        # noqa: E402
import matplotlib.gridspec as gridspec                 # noqa: E402

import fig_style as S

EXP = "<HOME>/gsoc2026-deeplense-qml/experiments/13_iqp_turbulence_replication"
OUT_TREE = os.path.join(EXP, "outputs_lens_class")
RUN_FMT = "%s_m4_mmdflat_resample_n100"

# (cache/dir name, row label as printed)
CLASSES = [("axion", "axion"), ("cdm", "cdm"), ("no_sub", "no sub")]
N_REAL = 2
N_GEN = 3


def load_rows():
    """[(label, real (2,64,64), gen (3,64,64))] -- first two held-out, first three generated."""
    sys.path.insert(0, EXP)
    import data_lens_class                              # noqa: E402
    import data_lens_r3                                 # noqa: E402

    rows = []
    for cname, label in CLASSES:
        data_lens_class.install(cname)
        d = data_lens_r3.load_r3(100, n_holdout=200)
        real = np.asarray(d.holdout_images[:N_REAL], dtype=np.float64)
        run = os.path.join(OUT_TREE, RUN_FMT % cname)
        if not os.path.isdir(run):
            raise SystemExit("figB_classes: missing run dir %s -- has submit_lens_class.sbatch "
                             "finished?" % run)
        gen = np.asarray([np.load(os.path.join(run, "generated_%03d.npy" % i))
                          for i in range(N_GEN)], dtype=np.float64)
        rows.append((label, real, gen))
    return rows


def make(outdir):
    S.apply_style()
    rows = load_rows()

    # 2 real | gap | 3 generated | colorbar
    widths = [1.0] * N_REAL + [0.24] + [1.0] * N_GEN + [0.085]
    fig = plt.figure(figsize=(S.TEXTWIDTH, 2.15))
    gs = gridspec.GridSpec(len(rows), len(widths), figure=fig, width_ratios=widths,
                           wspace=0.07, hspace=0.07,
                           left=0.105, right=0.925, bottom=0.012, top=0.845)

    im = None
    for i, (label, real, gen) in enumerate(rows):
        panels = [(j, real[j]) for j in range(N_REAL)]
        panels += [(N_REAL + 1 + j, gen[j]) for j in range(N_GEN)]
        for col, img in panels:
            ax = fig.add_subplot(gs[i, col])
            im = ax.imshow(img, cmap=S.IMG_CMAP, vmin=S.IMG_VMIN, vmax=S.IMG_VMAX,
                           interpolation="nearest", origin="lower")
            ax.set_xticks([]); ax.set_yticks([])
            for sp in ax.spines.values():
                sp.set_linewidth(0.4)
                sp.set_color("#b8b8b8")
            if col == 0:
                ax.set_ylabel(label, fontsize=7.5, rotation=0, ha="right", va="center",
                              labelpad=5)

    cax = fig.add_subplot(gs[:, len(widths) - 1])
    cb = fig.colorbar(im, cax=cax)
    cb.set_label("pixel intensity (a.u.)", fontsize=7.0, labelpad=2)
    cb.ax.tick_params(labelsize=7.0, width=0.5, length=2)
    cb.outline.set_linewidth(0.4)

    # group headers, centred over each block in figure coordinates
    def centre(c0, c1):
        a = fig.add_subplot(gs[0, c0]); b = fig.add_subplot(gs[0, c1])
        pa, pb = a.get_position(), b.get_position()
        a.set_visible(False); b.set_visible(False)
        return 0.5 * (pa.x0 + pb.x1), pa.y1

    x_real, y_top = centre(0, N_REAL - 1)
    x_gen, _ = centre(N_REAL + 1, N_REAL + N_GEN)
    fig.text(x_real, y_top + 0.048, "held-out (real)", fontsize=7.5, ha="center", va="bottom")
    fig.text(x_gen, y_top + 0.048, "generated, trained on this class only",
             fontsize=7.5, ha="center", va="bottom")

    return S.save(fig, outdir, "figB_classes")


if __name__ == "__main__":
    make(os.path.dirname(os.path.abspath(__file__)))
