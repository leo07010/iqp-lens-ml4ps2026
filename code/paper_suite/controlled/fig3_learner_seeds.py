#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""App. C (reference paper Fig. 3) repeated over LEARNER seeds, with the targets held fixed.

The published run (`submit_fig3_v2.sbatch`, results_fig3_v2.jsonl) is one learner seed.  The
claim it supports -- "more learner gates lower the whole MMD envelope, and inside the reachable
range the achieved MMD RISES with the target's QCLI" -- is about the learner, so the seed that
has to be repeated is the learner's, not the target family's.

What is held fixed (bit-for-bit identical to the published run, because it is generated by the
same rng streams in the same order):
    * the 140 target circuits, their SPSA/Adam trajectories, their selected snapshots and
      their 10^4-sample datasets          -> np.random.default_rng(--seed), consumed in the
                                             same order by build_targets/characterise_targets
    * each target's three-sigma kernel bandwidths -> resolve_sigmas_for_codes(..., --seed + b)
    * the three learner ARCHITECTURES (which <=2-local Pauli strings each G_n uses)
                                          -> np.random.default_rng(--seed + 777)
      This is deliberate: the study fixes ONE architecture per gate count, and at G_n = 150 the
      draw is not even random (136 = every <=2-local string that exists at n = 16).

What moves with --learner-seed: only the learner's initial angles,
    np.random.default_rng(--seed + 991 + G_n + 1_000_000 * learner_seed),
which reduces to the published stream at learner_seed = 0.  Training itself (Adam on the exact
closed-form MMD^2) has no other stochasticity, so this is the whole learner-side seed.

`--learner-seeds 0,...` therefore re-derives the published numbers and is the correctness check
for this script; the aggregator refuses to quote a seed table without it.

Output: one jsonl per learner seed, same row schema as fig3_support_mismatch.py plus a
"learner_seed" field on every row.

Python 3.9 compatible.  GPU strongly preferred (~15 min per learner seed on an H100).
"""
from __future__ import annotations

import argparse
import json
import math
import os
import sys
import time

import numpy as np
import torch

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import common                                                             # noqa: E402
import fig3_support_mismatch as F3                                        # noqa: E402
from common import (BatchIQP, popcount_index, random_gate_masks,          # noqa: E402
                    uniform_null_qcli)

_DTYPES = {"float32": torch.float32, "float64": torch.float64}


def parse_args(argv=None):
    p = argparse.ArgumentParser(description="App. C over learner seeds, targets held fixed.")
    # every knob of the published run, so the invocation can be copied verbatim
    p.add_argument("--n", type=int, default=16)
    p.add_argument("--gates-target", default="140,280,420,560,700,840,1050")
    p.add_argument("--learner-gates", default="50,100,150")
    p.add_argument("--locality-target", type=int, default=4)
    p.add_argument("--locality-learner", type=int, default=2)
    p.add_argument("--n-targets", type=int, default=20)
    p.add_argument("--n-samples", type=int, default=10000)
    p.add_argument("--target-steps", type=int, default=400)
    p.add_argument("--target-snapshots", type=int, default=400)
    p.add_argument("--target-optimizer", choices=("adam", "spsa"), default="adam")
    p.add_argument("--target-lr", type=float, default=0.05)
    p.add_argument("--target-qcli-max", type=float, default=0.7)
    p.add_argument("--spsa-a", type=float, default=1.0)
    p.add_argument("--spsa-c", type=float, default=0.2)
    p.add_argument("--target-init-std", type=float, default=0.05)
    p.add_argument("--steps", type=int, default=5000)
    p.add_argument("--lr", type=float, default=1e-4)
    p.add_argument("--learner-init-std", type=float, default=0.01)
    p.add_argument("--train-batch", type=int, default=70)
    p.add_argument("--null-reps", type=int, default=5)
    p.add_argument("--bin-width-report", type=float, default=0.09)
    p.add_argument("--exact-target-control", dest="exact_target_control",
                   action="store_true", default=True)
    p.add_argument("--no-exact-target-control", dest="exact_target_control",
                   action="store_false")
    p.add_argument("--dtype", choices=tuple(_DTYPES), default="float64")
    p.add_argument("--device", default="cuda")
    p.add_argument("--seed", type=int, default=20260907,
                   help="the TARGET seed; must stay at the published value to keep the "
                        "targets and the learner architectures fixed")
    p.add_argument("--progress-every", type=int, default=1000)
    # new
    p.add_argument("--learner-seeds", default="1,2,3,4",
                   help="comma-separated learner seeds; 0 reproduces the published run")
    p.add_argument("--out-prefix", default="results_fig3_v2_ls")
    p.add_argument("--out-dir", default=None)
    p.add_argument("--done-marker", default=None)
    return p.parse_args(argv)


def learner_rng(seed, learner_seed, gates_requested):
    """The published stream at learner_seed = 0, a disjoint one otherwise."""
    return np.random.default_rng(int(seed) + 991 + int(gates_requested)
                                 + 1000000 * int(learner_seed))


def main(argv=None):
    args = parse_args(argv)
    if args.device == "cpu":
        torch.set_num_threads(min(8, os.cpu_count() or 1))
    device = torch.device(args.device)
    dtype = _DTYPES[args.dtype]
    n = int(args.n)
    torch.manual_seed(int(args.seed))
    rng = np.random.default_rng(int(args.seed))
    pc_idx = popcount_index(n, device)
    g_data_list = [int(x) for x in str(args.gates_target).split(",") if x.strip()]
    g_learn_list = [int(x) for x in str(args.learner_gates).split(",") if x.strip()]
    ls_list = [int(x) for x in str(args.learner_seeds).split(",") if x.strip()]
    out_dir = args.out_dir or os.path.join(os.path.dirname(HERE), "..", "outputs_controlled")
    out_dir = os.path.abspath(out_dir)
    os.makedirs(out_dir, exist_ok=True)

    def log(msg):
        print(msg, flush=True)

    t_all = time.time()
    log("[fig3ls] n=%d device=%s targets/gate-count=%d learner_seeds=%s out_dir=%s"
        % (n, args.device, args.n_targets, ls_list, out_dir))

    # ---- the x-axis floor (identical to the published run) -----------------------------
    null_mean, null_std = uniform_null_qcli(n, args.n_samples, args.null_reps,
                                            int(args.seed) + 13)
    log("[fig3ls] i.i.d.-uniform null at M=%d: I_QCLI = %.4f +/- %.4f"
        % (args.n_samples, null_mean, null_std))

    # ---- learner architectures (FIXED; same rng stream as the published run) ------------
    rng_l = np.random.default_rng(int(args.seed) + 777)
    learners = []
    for g in g_learn_list:
        m, eff = random_gate_masks(n, args.locality_learner, g, rng_l)
        learners.append({"gates_requested": g, "gates_effective": eff, "masks": m})
        log("[fig3ls] learner G_n=%d -> %d distinct <=%d-local gates (fixed across seeds)"
            % (g, eff, args.locality_learner))

    # ---- targets, built ONCE and shared by every learner seed ---------------------------
    all_targets, all_ez, all_ez_exact = [], [], []
    for g_data in g_data_list:
        targets, sim = F3.build_targets(args, n, g_data, rng, device, dtype, pc_idx, log)
        ez, ez_ex = F3.characterise_targets(args, n, sim, targets, rng, device, dtype,
                                            pc_idx, log)
        for t in targets:
            t["target_id"] = len(all_targets)
            all_targets.append(t)
        all_ez.append(ez)
        all_ez_exact.append(ez_ex)
        del sim
    ez_all = torch.cat(all_ez, dim=0)
    ez_exact_all = torch.cat(all_ez_exact, dim=0)
    c_all = torch.as_tensor(np.stack([t["c_by_weight"] for t in all_targets]),
                            dtype=dtype, device=device)
    T = len(all_targets)
    qx = np.array([t["I_QCLI_exact"] for t in all_targets])
    qs = np.array([t["I_QCLI_sample"] for t in all_targets])
    log("[fig3ls] %d targets built (shared by all learner seeds). exact I_QCLI %.4f..%.4f; "
        "10^4-sample I_QCLI %.4f..%.4f; uniform null %.4f"
        % (T, qx.min(), qx.max(), qs.min(), qs.max(), null_mean))
    log("[fig3ls] target build + characterisation took %.1f s" % (time.time() - t_all))

    chunk = max(1, int(args.train_batch))
    arms = [("sample", ez_all, ez_exact_all)]
    if args.exact_target_control:
        arms.append(("exact", ez_exact_all, None))

    written = []
    for ls in ls_list:
        t_ls = time.time()
        path = os.path.join(out_dir, "%s%d.jsonl" % (args.out_prefix, ls))
        w = F3.JsonlWriter(path)
        w.write({"record": "null", "n": n, "learner_seed": ls,
                 "n_samples": int(args.n_samples), "null_reps": int(args.null_reps),
                 "I_QCLI_uniform_mean": null_mean, "I_QCLI_uniform_std": null_std})
        for t in all_targets:
            w.write({"record": "target", "learner_seed": ls, "target_id": t["target_id"],
                     "gates_target": t["gates_requested"],
                     "gates_target_effective": t["gates_effective"],
                     "snapshot": t["snap"], "qcli_level": t["qcli_level"],
                     "I_QCLI": t["I_QCLI_sample"], "I_CCI": t["I_CCI_sample"],
                     "I_QCLI_exact": t["I_QCLI_exact"], "I_CCI_exact": t["I_CCI_exact"],
                     "I_TC_sample": t["I_TC_sample"],
                     "n_distinct_codes": t["n_distinct_codes"], "traj": t["traj"],
                     "qcli_reached_pool": t["qcli_reached_pool"], "sigmas": t["sigmas"],
                     "n_samples": int(args.n_samples)})
        medians = {}
        for L in learners:
            rng_th = learner_rng(args.seed, ls, L["gates_requested"])
            simL = BatchIQP(n, L["masks"], device=device, dtype=dtype)
            theta0_all = simL.init_theta(T, rng_th, std=args.learner_init_std)
            res = {}
            for arm, ez_fit, ez_alt in arms:
                parts = []
                for lo in range(0, T, chunk):
                    hi = min(T, lo + chunk)
                    tag = "ls%d/G%d/%s[%d:%d]" % (ls, L["gates_requested"], arm, lo, hi)
                    parts.append(F3.fit_learner(args, n, L["masks"], ez_fit[lo:hi],
                                                c_all[lo:hi], device, dtype, pc_idx, log, tag,
                                                theta0=theta0_all[lo:hi],
                                                ez_alt=None if ez_alt is None else ez_alt[lo:hi]))
                res[arm] = {k: np.concatenate([p[k] for p in parts])
                            for k in ("final_mmd2", "best_mmd2", "init_mmd2", "floor_proxy",
                                      "final_mmd2_alt")}
            del simL
            for t in all_targets:
                i = t["target_id"]
                r = res["sample"]
                f2 = float(r["final_mmd2"][i])
                b2 = float(r["best_mmd2"][i])
                row = {"record": "fit", "learner_seed": ls, "target_id": i,
                       "gates_target": t["gates_requested"],
                       "gates_target_effective": t["gates_effective"],
                       "learner_gates": L["gates_requested"],
                       "learner_gates_effective": L["gates_effective"],
                       "I_QCLI": t["I_QCLI_sample"], "I_CCI": t["I_CCI_sample"],
                       "I_QCLI_exact": t["I_QCLI_exact"], "I_CCI_exact": t["I_CCI_exact"],
                       "final_mmd2": f2, "final_mmd": math.sqrt(max(f2, 0.0)),
                       "best_mmd2": b2, "best_mmd": math.sqrt(max(b2, 0.0)),
                       "init_mmd2": float(r["init_mmd2"][i]),
                       "mmd2_floor_proxy": float(r["floor_proxy"][i]),
                       "final_mmd2_vs_exact": float(r["final_mmd2_alt"][i]),
                       "steps": int(args.steps), "lr": float(args.lr),
                       "n_samples": int(args.n_samples), "n": n}
                if "exact" in res:
                    e = res["exact"]
                    e2 = float(e["final_mmd2"][i])
                    row["final_mmd2_exacttrained"] = e2
                    row["final_mmd_exacttrained"] = math.sqrt(max(e2, 0.0))
                    row["best_mmd2_exacttrained"] = float(e["best_mmd2"][i])
                    row["mmd2_floor_proxy_exact"] = float(e["floor_proxy"][i])
                w.write(row)
            medians[L["gates_requested"]] = float(np.median(res["sample"]["final_mmd2"]))
            log("[fig3ls] ls=%d learner G_n=%d: median MMD^2 %.4e"
                % (ls, L["gates_requested"], medians[L["gates_requested"]]))
        w.write({"record": "meta", "n": n, "seed": int(args.seed), "learner_seed": ls,
                 "learner_rng_seeds": {str(L["gates_requested"]):
                                       int(args.seed) + 991 + L["gates_requested"]
                                       + 1000000 * ls for L in learners},
                 "dtype": args.dtype, "device": str(args.device),
                 "gates_target": g_data_list, "learner_gates": g_learn_list,
                 "n_targets_per_gate_count": int(args.n_targets),
                 "n_samples": int(args.n_samples), "steps": int(args.steps),
                 "lr": float(args.lr), "target_steps": int(args.target_steps),
                 "locality_target": int(args.locality_target),
                 "locality_learner": int(args.locality_learner),
                 "target_optimizer": args.target_optimizer,
                 "target_lr": float(args.target_lr),
                 "target_level_axis": "exact_pmf_I_QCLI",
                 "target_qcli_max_reached": float(qx.max()),
                 "exact_target_control": bool(args.exact_target_control),
                 "I_QCLI_exact_span": [float(qx.min()), float(qx.max())],
                 "I_QCLI_sample_span": [float(qs.min()), float(qs.max())],
                 "I_QCLI_uniform_null": null_mean,
                 "median_final_mmd2": medians,
                 "wall_seconds": time.time() - t_ls})
        w.close()
        written.append(path)
        log("[fig3ls] learner seed %d -> %s (%.1f s)" % (ls, path, time.time() - t_ls))

    if args.done_marker:
        d = os.path.dirname(os.path.abspath(args.done_marker))
        if d:
            os.makedirs(d, exist_ok=True)
        with open(args.done_marker, "w") as f:
            f.write("fig3 learner seeds complete %s\n" % time.strftime("%Y-%m-%d %H:%M:%S"))
            f.write("learner_seeds=%s\n" % ls_list)
            for p in written:
                f.write("jsonl=%s\n" % p)
            f.write("targets=%d exact_QCLI=%.4f..%.4f\n" % (T, qx.min(), qx.max()))
            f.write("wall_seconds=%.1f\n" % (time.time() - t_all))
    log("[fig3ls] wrote %d files in %.1f s" % (len(written), time.time() - t_all))
    return 0


if __name__ == "__main__":
    sys.exit(main())
